/** Display-only wording; stored codes, statuses and backup fields stay unchanged. */
export function plainMessage(message: string): string {
  if (message.startsWith('Invalid backup:')) return 'This file is not a supported backup. Choose a backup downloaded from this app.';
  if (message.startsWith('Conflicting ')) return 'This backup contains a different version of something already saved. Nothing will be replaced. Use a fresh product list to restore the older backup.';
  if (message.includes('Duplicate IDs within backup')) return 'This backup contains repeated records. Choose an original backup downloaded from this app.';
  if (message.includes('missing product/source') || message.includes('missing entities') || message.includes('missing products')) return 'Some products, codes or source details are missing from this backup. Choose a complete backup.';
  return message
    .replaceAll('Public data cannot establish packaging or POS verification.', 'Online product information cannot show that this code was checked on the package or at the register.')
    .replaceAll('Establish a supported code type before verification.', 'Choose the correct code type before marking this code checked.')
    .replaceAll('Packaging verification requires a packaging source.', 'To mark it checked on the package, choose the package as your source.')
    .replaceAll('Backup imported without trusted valid personal verification; original state retained here.', 'This code was added from a backup and needs checking. The earlier check is kept below.')
    .replaceAll('Explicitly trusted personal backup restore; existing history preserved.', 'Restored from your own backup. Earlier changes are still saved.')
    .replaceAll('Backup imported for personal review.', 'Added from a backup for you to check.')
    .replaceAll('Public import defaults to unverified.', 'Online codes need checking before checkout.')
    .replaceAll('Product metadata edited:', 'Product details changed:')
    .replaceAll('Restoring modified demo records over untouched built-in placeholders. Existing user edits are never overwritten.', 'Restoring edited examples over unchanged starting examples. Your existing edits will not be replaced.')
    .replaceAll('Fictional candidate code — never use at checkout.', 'Made-up example code — do not use at checkout.')
    .replaceAll('Not checkout-ready. Requires manual review.', 'Not ready to use. Check this code before checkout.')
    .replaceAll('Checked against packaging only. Register compatibility has not been verified.', 'Checked on the package only. It has not been checked at the register.')
    .replaceAll('POS verified. Confirm the exact product before using your existing register.', 'Checked at the register. Make sure the brand and product match before use.')
    .replaceAll('Retired code — do not use at checkout.', 'No longer in use — do not use at checkout.')
    .replaceAll('Rejected code — do not use at checkout.', 'Marked incorrect — do not use at checkout.')
    .replaceAll('Invalid code — do not use at checkout, even if previously marked verified.', 'This code needs correcting. Do not use it, even if it was checked before.')
    .replaceAll('Unknown code type — establish a supported identifier type before checkout use.', 'Choose the correct code type before using this code at checkout.')
    .replaceAll('This record changed in another operation. Reload its details before editing.', 'These details have changed since you opened them. Reopen the product before editing.')
    .replaceAll('History is append-only.', 'Past changes cannot be edited or removed.')
    .replaceAll('Invalid URL', 'That website link is not valid. Check the address and try again.')
    .replaceAll('Code must contain ASCII digits only, without spaces.', 'Use numbers 0–9 only, without spaces or other characters.')
    .replaceAll('including the check digit.', 'including the final checking digit.')
    .replaceAll('Check digit does not match. Review the original code; it has not been corrected automatically.', 'The final digit does not match the rest of the code. Check every number against the package. Nothing was changed automatically.')
    .replaceAll('Length and check digit valid. This does not prove product identity or register compatibility.', 'The numbers pass the barcode check. You still need to check the exact product and whether the register accepts it.')
    .replaceAll('Numeric format only. No UPC/EAN checksum or store compatibility is implied.', 'This is a numbers-only code. Check that it belongs to this product and works at your store.')
    .replaceAll('Duplicate identifier association', 'This code is already linked to another saved entry')
    .replaceAll('duplicate identifier association', 'code linked to more than one entry')
    .replaceAll('Duplicate active code', 'Code already in use')
    .replaceAll('retained for review with barcode/copy disabled.', 'kept for checking, without barcode display or copying.')
    .replaceAll('Review the association before importing.', 'Check which product it belongs to before restoring this file.')
    .replaceAll('Demo cannot be verified', 'Example cannot be marked as checked')
    .replaceAll('Fictional demo products cannot be verified.', 'Made-up examples cannot be marked as checked.')
    .replaceAll('Choose a supported verification status.', 'Choose how this code was checked.')
    .replaceAll('before assigning or verifying this code', 'before linking or checking this code')
    .replaceAll('identifier associations', 'links between codes and products')
    .replaceAll('identifier association', 'link between a code and product')
    .replaceAll('incorrect association', 'incorrect link')
    .replaceAll('No active identifiers', 'No codes in use')
    .replaceAll('Unverified code', 'Code not checked')
    .replaceAll('Register compatibility unverified', 'Not checked at the register')
    .replaceAll('Invalid code', 'Code needs correcting')
    .replaceAll('Unknown identifier type', 'Code type needs checking')
    .replaceAll('Active identifier no longer exists.', 'This code is no longer in use. Reopen the product to see its latest details.')
    .replaceAll('Product no longer exists.', 'This product is no longer saved.')
    .replaceAll('identifier type', 'code type')
    .replaceAll('identifier', 'code')
    .replaceAll('Retiring', 'Stopping use of')
    .replaceAll('retire', 'stop using')
    .replaceAll('Image and source URLs must use HTTP or HTTPS.', 'Use a website link starting with http:// or https:// for the photo or source.')
    .replaceAll('Record image attribution when attaching an image reference.', 'Add the photo owner or website when including a photo link.')
    .replaceAll('attribution', 'credit')
    .replaceAll('before checkout use', 'before using them at checkout')
    .replaceAll('before verification', 'before marking it checked')
    .replaceAll('establish', 'confirm')
    .replaceAll('checksum', 'barcode number check')
    .replaceAll('POS', 'register')
    .replaceAll('packaging verification', 'checking the package')
    .replaceAll('Packaging verification', 'Checking the package')
    .replaceAll('Public data', 'Online product information')
    .replaceAll('public candidate', 'online product suggestion')
    .replaceAll('public product', 'online product')
    .replaceAll('cached online product suggestion', 'saved online product suggestion')
    .replaceAll('cached', 'previously saved')
    .replaceAll('personal-import limit', 'file size limit')
    .replaceAll('valid JSON', 'a readable backup file')
    .replaceAll('No previous value', 'Not recorded before');
}
export function displayDate(value: string): string {
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? value : date.toLocaleString();
}
