it('refreshes displayed verified artwork when another operation corrects the stored identifier', async () => {
  const { store, user } = setup();
  const product = await store.createProduct({ ...demoProducts[0], name: 'Synthetic observed product' }, 'Test fixture');
  const initial = await store.addIdentifier(product.id, { code: '012345678905', type: 'UPC_A', source: { type: 'manual', attribution: 'Test fixture' }, reason: 'Create' });
  const verified = await store.verifyIdentifier(initial.id, { status: 'pos_verified', confirmed: true, source: { type: 'manual', attribution: 'Test evidence' }, reason: 'Checked' }, initial.updatedAt);
  render(<App store={store} />); await screen.findByText('7 products');
  await user.click(screen.getByRole('button', { name: /Synthetic observed product/ }));
  await screen.findByRole('img', { name: /barcode/ });
  await store.correctIdentifier(initial.id, { code: '036000291452', type: 'UPC_A', source: { type: 'manual', attribution: 'Corrected test evidence' }, reason: 'Correct' }, verified.updatedAt);
  await waitFor(() => expect(screen.queryByRole('img', { name: /barcode/ })).toBeNull());
  expect(screen.getByText('036000291452')).toBeVisible();
});
